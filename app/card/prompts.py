def build_user_message(product: ProductInput, missing_fields: list[str]) -> str:
    data = json.dumps(product.model_dump(), ensure_ascii=False, indent=2)
    missing = "\n".join(f"- {field}" for field in missing_fields) or "нет"
    return (
        f"<product_data>\n{data}\n</product_data>\n\n"
        f"Поля без данных (их значения не придумывай):\n{missing}\n\n"
        "Подготовь карточку товара."
    )


def build_repair_message(problems: list[str]) -> str:
    listed = "\n".join(f"- {problem}" for problem in problems)
    return (
        f"Автоматическая проверка нашла проблемы:\n{listed}\n\n"
        "Исправь их и верни карточку целиком. Правила те же: если значение нельзя подтвердить "
        "данными из <product_data>, убери его из текста, "
        f"а в key_characteristics укажи «{NO_DATA}»."
    )
